// Regenerates src/content/blog/index.ts from the article files in that folder,
// so adding a post is just dropping `<slug>.ts` next to the others.
// Runs automatically before `dev` and `build`.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const blogDir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "content", "blog");
const files = (await readdir(blogDir))
  .filter((file) => file.endsWith(".ts") && file !== "index.ts")
  .sort();

const identifier = (file) => `post_${file.replace(/\.ts$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;

const contents = `// AUTO-GENERATED by scripts/generate-blog-index.mjs — do not edit by hand.
// Add an article by creating src/content/blog/<slug>.ts that exports \`post\`.
import type { BlogPost } from "@/lib/content-types";
${files.map((file) => `import { post as ${identifier(file)} } from "./${file.replace(/\.ts$/, "")}";`).join("\n")}

export const BLOG_POST_ENTRIES: BlogPost[] = [
${files.map((file) => `  ${identifier(file)},`).join("\n")}
];
`;

const indexPath = join(blogDir, "index.ts");
const previous = await readFile(indexPath, "utf8").catch(() => "");
if (previous !== contents) {
  await writeFile(indexPath, contents);
  console.log(`Blog index updated with ${files.length} article(s).`);
}
